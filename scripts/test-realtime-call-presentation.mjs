import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,rmSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import ts from 'typescript';

// Presentation state only: no microphone/camera, sockets, user history,
// running service, timers or real model is accessed by these assertions.
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const temporary=mkdtempSync(join(tmpdir(),'zhiyu-realtime-call-presentation-'));
try {
  const source=readFileSync(join(root,'lib/npc/realtime-call-presentation.ts'),'utf8');
  writeFileSync(join(temporary,'presentation.mjs'),ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText);
  const {CAPTION_IDLE_HIDE_MS,createCallCaptionWindow,callCaptionWindowReducer:reduce,getCallCaptionFrame:frame,callElapsedMs,formatCallDuration}=await import(pathToFileURL(join(temporary,'presentation.mjs')));
  const user=(id,text,final=false)=>({id,role:'user',text,final});
  const assistant=(id,text,final=false)=>({id,role:'assistant',text,final});
  assert.equal(CAPTION_IDLE_HIDE_MS,4000);
  let state=createCallCaptionWindow();
  assert.equal(frame(state).hidden,true);
  const original=Object.freeze(user('user-one','我想'));
  state=reduce(state,{type:'transcript',line:original,now:0});
  state=reduce(state,{type:'transcript',line:user('user-one','我想跟你聊聊'),now:200});
  assert.equal(state.current.id,'user-one');assert.equal(state.current.text,'我想跟你聊聊');assert.equal(state.previous,undefined);
  assert.equal(original.text,'我想','input snapshots are never mutated or concatenated');
  state=reduce(state,{type:'transcript',line:user('user-one','我想跟你聊聊',true),now:400});
  assert.equal(state.previous,undefined,'a final of the same turn is not a new sentence');
  assert.equal(reduce(state,{type:'transcript',line:user('user-one','我想跟你聊聊',true),now:900}),state,'duplicate finals do not reset the idle clock');
  state=reduce(state,{type:'phase',phase:'thinking',now:500});
  assert.equal(frame(state).waiting,true);assert.equal(frame(state).current,undefined);assert.equal(frame(state).previous.id,'user-one');
  assert.equal(reduce(state,{type:'tick',now:10000}),state,'thinking dots remain visible without creating a fake turn');
  state=reduce(state,{type:'transcript',line:assistant('assistant-one','你说'),now:600});
  const previousId=state.previous.id,currentId=state.current.id;
  state=reduce(state,{type:'transcript',line:assistant('assistant-one','你说，我在听。'),now:700});
  assert.equal(state.previous.id,previousId);assert.equal(state.current.id,currentId);assert.equal(state.current.text,'你说，我在听。');assert.equal(frame(state).waiting,false);
  state=reduce(state,{type:'phase',phase:'speaking',now:800});
  state=reduce(state,{type:'transcript',line:assistant('assistant-one','你说，我在听。',true),now:900});
  assert.equal(reduce(state,{type:'tick',now:100000}),state,'text can be final while its audio is still playing');
  state=reduce(state,{type:'phase',phase:'listening',now:2000});
  assert.equal(reduce(state,{type:'tick',now:5999}).hidden,false);
  state=reduce(state,{type:'tick',now:6000});
  assert.equal(state.hidden,true);assert.equal(state.current.id,'assistant-one','the fade retains its rows for CSS opacity animation');
  state=reduce(state,{type:'transcript',line:user('user-two','今天很累'),now:7000});
  assert.equal(state.hidden,false);assert.equal(state.previous,undefined,'speech after the fade does not revive the old previous/current sentence');
  assert.equal(state.current.id,'user-two');
  state=reduce(state,{type:'transcript',line:assistant('assistant-two','先歇一会儿'),now:7100});
  assert.equal(state.previous.id,'user-two');assert.equal(state.current.id,'assistant-two');
  state=reduce(state,{type:'transcript',line:user('user-three','好'),now:7200});
  assert.equal(state.previous.id,'assistant-two');assert.equal(state.current.id,'user-three','a third sentence drops the old previous line');
  const beforeLate=state.lastActivityAt;
  state=reduce(state,{type:'transcript',line:assistant('assistant-two','先歇一会儿。',true),now:7300});
  assert.equal(state.current.id,'user-three');assert.equal(state.previous.text,'先歇一会儿。');assert.equal(state.lastActivityAt,beforeLate,'late final updates in place without promoting or extending idle');
  assert.equal(reduce(state,{type:'transcript',line:user('user-one','旧句',true),now:7400}),state,'an older turn outside the window cannot return');
  state=reduce(state,{type:'phase',phase:'thinking',now:7500});
  assert.equal(frame(state).previous.id,'user-three');assert.equal(frame(state).current,undefined);
  state=reduce(state,{type:'transcript',line:assistant('assistant-three','我陪你'),now:7600});
  state=reduce(state,{type:'interrupt',now:7700});
  assert.equal(state.current.text,'我陪你');assert.equal(state.current.interrupted,true);
  assert.equal(reduce(state,{type:'transcript',line:assistant('assistant-three','迟到的完整回复',true),now:7800}),state,'an interrupted sentence stops at the displayed text');
  state=reduce(state,{type:'transcript',line:user('user-four','等等'),now:7900});
  assert.equal(state.previous.text,'我陪你');assert.equal(state.current.text,'等等');
  const roles=reduce(reduce(createCallCaptionWindow(),{type:'transcript',line:user('shared-turn','我说'),now:0}),{type:'transcript',line:assistant('shared-turn','我听着'),now:1});
  assert.equal(roles.previous.role,'user');assert.equal(roles.current.role,'assistant','speaker identity distinguishes rows even if a transport reuses the turn ID');
  const noFinal=reduce(createCallCaptionWindow(),{type:'transcript',line:user('partial-without-final','暂时只有中间结果'),now:0});
  assert.equal(reduce(noFinal,{type:'tick',now:4000}).hidden,true,'a missing final cannot hold a silent listening caption forever');
  const faded=reduce(noFinal,{type:'tick',now:4000});
  const waiting=reduce(faded,{type:'phase',phase:'thinking',now:5000});
  assert.equal(frame(waiting).previous,undefined);assert.equal(frame(waiting).waiting,true,'thinking after silence starts without stale sentences');
  const reset=reduce(state,{type:'reset'});
  assert.deepEqual(reset,createCallCaptionWindow());assert.equal(reduce(reset,{type:'tick',now:999999}),reset,'hangup/retry cleanup leaves no caption activity to tick');

  assert.equal(callElapsedMs(null,10000),0,'opening/connecting time is excluded until ready');
  assert.equal(callElapsedMs(10000,10000),0);
  assert.equal(callElapsedMs(10000,12450),2450);
  assert.equal(callElapsedMs(10000,50000,15400),5400,'ending freezes the duration regardless of later ticks');
  assert.equal(callElapsedMs(10000,1000),0);assert.equal(callElapsedMs(NaN,20000),0);assert.equal(callElapsedMs(0,Infinity),0);
  for(const [milliseconds,label] of [[0,'00:00'],[999,'00:00'],[1000,'00:01'],[59999,'00:59'],[60000,'01:00'],[222000,'03:42'],[3599999,'59:59'],[3600000,'1:00:00'],[3661000,'1:01:01'],[-1000,'00:00'],[Infinity,'00:00']])assert.equal(formatCallDuration(milliseconds),label);
  console.log('PASS caption presentation: full-snapshot updates, two sentences, real IDs, thinking dots, speaking/final distinction, 4-second idle fade, clean resumption, late/interrupted rows and reset.');
  console.log('PASS call timing: ready-only elapsed time, frozen hangup duration and mm:ss/h:mm:ss formatting.');
} finally {rmSync(temporary,{recursive:true,force:true});}
